def node_text(t):
    return "".join(c.data for c in t.childNodes if c.nodeType == c.TEXT_NODE)


def set_node_text(t, s):
    for c in list(t.childNodes):
        t.removeChild(c)
    t.appendChild(dom.createTextNode(s))


def para_t(p, i=0):
    return p.getElementsByTagName("w:t")[i]


