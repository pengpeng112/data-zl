    --state-db "$APP_DB_URL" \
    --approval-ref "T1-BACKFILL-B9-20261027:$LOW" \
    --executor-code sql-target-apply-1 \
    --target-scope "10.10.8.74:1521/orcl.DBOPER.$T" \
    --registered-by "用户会话批准2026-10-27(批9ODS历史回补25表派工)" \
