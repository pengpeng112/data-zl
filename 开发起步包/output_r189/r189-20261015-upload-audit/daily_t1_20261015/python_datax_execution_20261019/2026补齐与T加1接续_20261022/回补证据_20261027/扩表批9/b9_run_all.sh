#!/bin/sh
# 批9 逐表进程隔离外层循环：一表一个 python 进程（SIGSEGV 只连坐本表）。
# 顺序=b9_exec_order.json（小差距先通、大表殿后）；崩溃表记录后继续。
cd /app || exit 1
DRIVER=/opt/data-asset/t1-stage/b9_backfill_one.py
LOG=/opt/data-asset/t1-stage/b9_run_all.log
TABLES="EMR_HOS_SUCCESSION_RECORD EMR_REFERRAL_HOS_RECORD EMR_HOS_DIFFIC_CASE_DISCUSS EMR_DEATH_RECORD EMR_ANES_RECORD_BLOOD EMR_INFOR_TRANS_BLOOD EMR_INFOR_CRITICALLY_ILL EMR_ICH_ALLERGIES EMR_OPERATION_NURSING EMR_BOFORE_OPERA_RECORD EMR_AFTER_OPERA_RECORD EMR_ANESTHESIA_RECORD EMR_INFOR_ANESTHESIA EMR_HOS_POSTOPER_RECORD EMR_HOS_PREOP_DISCUSS EMR_DISCHARGE_RECORD EMR_IN_FEE_INFO_MAIN EMR_HOS_CONSUL_RECORD EMR_ADMISSION_DIAGNOSIS EMR_OUTPATIENT_RECIPE EMR_OUTPATIENT_RECORD EMR_OUTPATIENT_REGISTER EMR_OUTPATIENT_RECIPE_ITEM EMR_DOC_ORDER_CHECK EMR_HOS_CHANGE_MAJOR_RECORD"
# 说明：HOS_CHANGE_MAJOR_RECORD（首试 SIGSEGV，视图重族）挪至末位殿后重试一次；
# 其余按差距升序。崩溃表由幂等跳过逻辑保护，重跑安全。
for T in $TABLES; do
  echo "#### RUN $T $(date '+%F %T') ####" >> "$LOG"
  python "$DRIVER" "$T" >> "$LOG" 2>&1
  RC=$?
  echo "#### EXIT $T rc=$RC $(date '+%F %T') ####" >> "$LOG"
done
echo "B9_RUN_ALL_DONE $(date '+%F %T')" >> "$LOG"
